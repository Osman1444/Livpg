/** Alignment geometry and grid snapping regression checks. */
const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const context = vm.createContext({ document: {querySelector: () => ({style:{}})}, finishTextEditing() {}, checkpoint() {} });
for (const file of ['state','alignment','constraints']) vm.runInContext(fs.readFileSync(`js/${file}.js`, 'utf8'),context);
const run = source => vm.runInContext(source,context);
const near = (actual, expected) => assert.ok(Math.abs(actual - expected) < 1e-8, `${actual} != ${expected}`);
run("P=[{e:[{id:1,x:10,y:20,w:100,h:50}]}];sel=1;W=800;H=1000;M.grid={margin:20}");
run("alignElements('right')");
near(run('selectedEl().x'),680);
run("alignElements('middle')");
near(run('selectedEl().y'),475);
run("selectedEl().a=90; alignElements('left')");
near(run('elementBounds(selectedEl()).left'),20);
run("alignElements('bottom')");
near(run('elementBounds(selectedEl()).bottom'),980);
run("P=[{e:[{id:1,x:10,y:20,w:100,h:50},{id:2,x:200,y:100,w:50,h:80}]}];sel=1;selection.add(1);selection.add(2);alignElements('left')");
near(run('P[0].e[0].x'),20);
near(run('P[0].e[1].x'),20);
run("alignmentTarget='page';alignElements('center')");
near(run('P[0].e[0].x + P[0].e[0].w/2'),400);
near(run('P[0].e[1].x + P[0].e[1].w/2'),400);
run("M.grid={};P=[{e:[{id:1,x:0,y:0,w:20,h:20},{id:2,x:40,y:30,w:40,h:40},{id:3,x:180,y:180,w:20,h:20}]}];selection.add(3);distributeElements('x')");
near(run('P[0].e[1].x'),80);
near(run('P[0].e[0].x'),0);
near(run('P[0].e[2].x'),180);
run("distributeElements('y')");
near(run('P[0].e[1].y'),80);
run("M.grid={snap:true,spacing:20,margin:10}");
const snapped = run("snapDrag(12,18,{left:15,top:22,right:115,bottom:102})");
near(snapped.dx,15); near(snapped.dy,28);
near(run("snapDrag(12,18,{left:15,top:22,right:115,bottom:102},true).dx"),12);
run('M.grid.snap=false');
near(run("snapDrag(12,18,{left:15,top:22,right:115,bottom:102}).dy"),18);
run("M.grid={spacing:999,margin:999}");
near(run('gridSettings().spacing'),200);
assert.ok(run('gridSettings().margin') < 400);
console.log('Passed: page/selection alignment, rotation bounds, equal gaps, grid limits and Alt snap bypass');
